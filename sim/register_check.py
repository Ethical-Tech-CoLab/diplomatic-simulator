#!/usr/bin/env python3
"""Lexical register check: do delegations coded with the same communication
register sound more alike than delegations coded differently?

Reads the six multi-party sessions from diplomacy-demo/data.js and the
`behavioralProfile.communicationRegister.level` of each delegation from
sim/scenarios/<scenario>/profiles/*.json. For every pair of delegations in a
scenario it computes two surface measures over their pooled statements:

  cosine   - cosine similarity of content-word frequency vectors (stopwords and
             tokens shorter than three letters removed);
  4-grams  - number of distinct word 4-grams the two delegations share.

It then compares the mean of each measure across same-register pairs with the
mean across different-register pairs. Runs locally with no model calls.

Usage: python3 sim/register_check.py [out.md]
"""
import glob, json, math, os, re, sys
from collections import Counter
from itertools import combinations

ROOT = os.path.join(os.path.dirname(__file__), "..")
DATA = os.path.join(ROOT, "diplomacy-demo", "data.js")
SCEN = [
    ("arctic", "sess-arctic-iscne-01"),
    ("centralasia", "sess-centralasia-iscne-01"),
    ("cyprus", "sess-cyprus-iscne-01"),
    ("scs", "sess-scs-iscne-01"),
    ("korea", "sess-korea-iscne-01"),
    ("kashmir", "sess-kashmir-iscne-01"),
]
STOP = set("""a an and are as at be been but by for from has have had he her his if in
into is it its of on or our ours that the their them these they this to was we were
what when where which while who whom will with would you your not no nor so than then
there here can could should may might must shall do does did done any all both each
more most other some such only own same too very just also over under before after
above below up down out off again further once because until about against between
through during how why one two three first second third let us me my i him she
ours yours itself themselves himself herself ourselves yourselves""".split())


def tokens(text):
    return [t for t in re.findall(r"[a-z']+", text.lower())
            if len(t) >= 3 and t not in STOP]


def cosine(a, b):
    num = sum(a[k] * b.get(k, 0) for k in a)
    da = math.sqrt(sum(v * v for v in a.values()))
    db = math.sqrt(sum(v * v for v in b.values()))
    return num / (da * db) if da and db else 0.0


def ngrams(toks, n=4):
    return set(tuple(toks[i:i + n]) for i in range(len(toks) - n + 1))


def mean(xs):
    return sum(xs) / len(xs) if xs else float("nan")


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else None
    src = open(DATA).read()
    d = json.loads(src[src.index("{"):src.rindex("}") + 1])
    sessions = {s["id"]: s for s in d["sessions"]}
    lines = ["# Register check: lexical similarity by communication register",
             "",
             "Generated by `sim/register_check.py` from `diplomacy-demo/data.js` and the",
             "profile `behavioralProfile.communicationRegister` labels. No model calls.",
             "",
             "For each scenario, every pair of delegations is compared on two surface",
             "measures over their pooled statements: cosine similarity of content-word",
             "frequencies, and the number of distinct word 4-grams they share. Pairs are",
             "then split by whether the two delegations carry the same register label.",
             "If register predicts voice, same-register pairs should score higher.",
             ""]
    pooled_same, pooled_diff = [], []
    pooled_same_ng, pooled_diff_ng = [], []
    for key, sid in SCEN:
        s = sessions[sid]
        reg = {}
        for f in glob.glob(os.path.join(ROOT, "sim", "scenarios", key, "profiles", "*.json")):
            p = json.load(open(f))
            reg[p["teamTwinName"]] = ((p.get("behavioralProfile") or {})
                                      .get("communicationRegister", {}).get("level", "?"))
        name = {p["teamTwinName"]: p["displayName"] for p in s["parties"]}
        texts = {}
        for m in s.get("moves", []):
            texts.setdefault(m["partyTwin"], []).append(m.get("text", ""))
        toks = {tw: tokens(" ".join(v)) for tw, v in texts.items()}
        vec = {tw: Counter(t) for tw, t in toks.items()}
        ng = {tw: ngrams(t) for tw, t in toks.items()}
        rows = []
        for a, b in combinations(sorted(texts), 2):
            c = cosine(vec[a], vec[b])
            shared = len(ng[a] & ng[b])
            same = reg.get(a) == reg.get(b)
            rows.append((c, shared, same, a, b))
            (pooled_same if same else pooled_diff).append(c)
            (pooled_same_ng if same else pooled_diff_ng).append(shared)
        same_c = [r[0] for r in rows if r[2]]
        diff_c = [r[0] for r in rows if not r[2]]
        same_n = [r[1] for r in rows if r[2]]
        diff_n = [r[1] for r in rows if not r[2]]
        lines.append(f"## {key} ({sid})")
        lines.append("")
        lines.append("Registers: " + ", ".join(
            f"{name.get(tw, tw)} = {reg.get(tw, '?')}" for tw in sorted(texts)))
        lines.append("")
        lines.append("| pairs | n | mean cosine | mean shared 4-grams |")
        lines.append("|---|---|---|---|")
        lines.append(f"| same register | {len(same_c)} | {mean(same_c):.3f} | {mean(same_n):.1f} |")
        lines.append(f"| different register | {len(diff_c)} | {mean(diff_c):.3f} | {mean(diff_n):.1f} |")
        lines.append("")
        rows.sort(reverse=True)
        lines.append("Most similar pairs by cosine:")
        lines.append("")
        for c, shared, same, a, b in rows[:3]:
            lines.append(f"- {name.get(a, a)} / {name.get(b, b)}: cosine {c:.3f}, "
                         f"{shared} shared 4-grams, registers "
                         f"{reg.get(a, '?')} / {reg.get(b, '?')}"
                         f"{' (same)' if same else ''}")
        lines.append("")
    lines.append("## Pooled across the six scenarios")
    lines.append("")
    lines.append("| pairs | n | mean cosine | mean shared 4-grams |")
    lines.append("|---|---|---|---|")
    lines.append(f"| same register | {len(pooled_same)} | {mean(pooled_same):.3f} | {mean(pooled_same_ng):.1f} |")
    lines.append(f"| different register | {len(pooled_diff)} | {mean(pooled_diff):.3f} | {mean(pooled_diff_ng):.1f} |")
    lines.append("")
    text = "\n".join(lines) + "\n"
    if out:
        open(out, "w").write(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
